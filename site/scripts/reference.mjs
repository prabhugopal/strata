// Generates the configuration and CLI reference pages from the source, so they can't drift:
// every key in each module's reference.conf (its comment, default and environment variable),
// and the strata CLI's own --help. Runs before dev and build.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';

const root = new URL('../..', import.meta.url).pathname;
const modules = [
  ['strata-core', 'Runtime, entities, HTTP, management, durability, timers, the seal'],
  ['strata-pekko', 'The Pekko runtime: clustering'],
  ['strata-store-jdbc', 'The JDBC store'],
  ['strata-http', 'The Pekko HTTP server'],
  ['strata-clojure', 'Clojure entities'],
];
// Pekko's own settings, passed through under strata.pekko.system: documented by Pekko, not listed here.
const SKIP = /^strata\.pekko\.system\./;

/** Keys of a HOCON file with the comment above each, its default and its environment override. */
function parse(text) {
  const keys = new Map();
  const stack = [];
  let comment = [];
  const lines = text.split('\n');
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (!line) { comment = []; continue; }
    if (line.startsWith('#')) { comment.push(line.replace(/^#\s?/, '')); continue; }
    if (line === '}') { stack.pop(); comment = []; continue; }
    const block = /^([\w.\-"$]+)\s*\{$/.exec(line);
    if (block) { stack.push(block[1]); comment = []; continue; }
    const kv = /^([\w.\-"$]+)\s*=\s*(.*)$/.exec(line);
    if (!kv) continue;
    let [, key, value] = kv;
    if (value.startsWith('[') && !value.includes(']')) {     // a list over several lines
      while (i + 1 < lines.length && !lines[i].includes(']')) value += ' ' + lines[++i].trim().replace(/#.*$/, '');
    }
    const path = [...stack, key].join('.').replaceAll('"', '');
    const env = /^\$\{\?(\w+)\}$/.exec(value);
    if (env) { const k = keys.get(path); if (k) k.env.push(env[1]); continue; }
    if (!keys.has(path)) keys.set(path, { path, value: value.replace(/\s+/g, ' ').trim(), doc: comment.join(' '), env: [] });
    comment = [];
  }
  return [...keys.values()].filter(k => !SKIP.test(k.path));
}

const cell = s => s.replaceAll('|', '\\|').replaceAll('\n', ' ');
/** Comment text as MDX-safe prose: <, { and } are markup in MDX. */
const prose = s => cell(s).replaceAll('<', '&lt;').replaceAll('{', '&#123;').replaceAll('}', '&#125;');
let out = `---
title: Configuration
description: Every Strata setting, its default and its environment variable. Generated from the reference.conf files.
---

{/* Generated by site/scripts/reference.mjs from each module's reference.conf. Don't edit: change the .conf. */}

Strata reads its settings with [Typesafe Config](https://github.com/lightbend/config). Every
default below lives in a module's \`reference.conf\`; override any key in your \`application.conf\`,
with \`-Dkey=value\`, with \`--key=value\` arguments to \`Strata.run\` / \`StrataMain\`, with the
environment variable shown, or (in Spring apps) under \`strata:\` in \`application.yaml\`.
`;
for (const [mod, about] of modules) {
  const file = join(root, mod, 'src/main/resources/reference.conf');
  if (!existsSync(file)) continue;
  const keys = parse(readFileSync(file, 'utf8'));
  out += `\n## ${mod}\n\n${about}.\n\n| Key | Default | Environment | What it does |\n|---|---|---|---|\n`;
  for (const k of keys) out += `| \`${k.path}\` | \`${cell(k.value)}\` | ${k.env.map(e => '`' + e + '`').join(' ') || ''} | ${prose(k.doc)} |\n`;
}
out += `\nPekko's own settings can be given under \`strata.pekko.system.pekko.*\`; see the [Pekko documentation](https://pekko.apache.org/docs/pekko/current/general/configuration-reference.html).\n`;
writeFileSync(new URL('../src/content/docs/reference/configuration.mdx', import.meta.url), out);

// The CLI's own help, when it's been built.
const bin = join(root, 'cli/target/debug/strata');
let cli = `---
title: The strata CLI
description: Every command of the strata command-line tool. Generated from its --help.
---

{/* Generated by site/scripts/reference.mjs from \`strata --help\`. */}

Install it with \`cargo install --path cli/strata-cli\` from the repository. Servers are kept in
\`~/.strata/config.toml\` (or \`$STRATA_HOME\`), readable only by you; tokens are read from stdin
(\`--token-stdin\`) or \`STRATA_TOKEN\`, never from arguments.
`;
if (existsSync(bin)) {
  const help = args => execFileSync(bin, [...args, '--help'], { encoding: 'utf8' }).trim();
  cli += '\n```text\n' + help([]) + '\n```\n';
  for (const sub of ['server', 'info', 'cluster', 'types', 'entities', 'get', 'call', 'events', 'metrics']) {
    cli += `\n## strata ${sub}\n\n\`\`\`text\n${help([sub])}\n\`\`\`\n`;
  }
} else {
  cli += '\n:::note\nBuild the CLI (`cd cli && cargo build`) and rebuild the site to list its commands here.\n:::\n';
}
writeFileSync(new URL('../src/content/docs/reference/cli.mdx', import.meta.url), cli);
console.log('reference pages generated');
