package io.strata.gradle;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * Kubernetes YAML for a Strata cluster: a StatefulSet (stable pod names, so nodes find each
 * other through a headless Service), an HTTP Service, a PodDisruptionBudget, and optionally a
 * development PostgreSQL. Probes use the management API's health endpoints.
 */
final class Manifests {
    private Manifests() {}

    record Params(String name, String namespace, String image, int replicas, int httpPort, int remotingPort,
                  String serviceType, String cpu, String memory, int maxRamPercentage, int graceSeconds,
                  String managementBase, boolean postgres, String postgresImage, String postgresStorage,
                  String database, String user, String jdbcUrl, Map<String, String> env,
                  String tlsSecret, String tlsMountPath, String splitBrain, int startupSeconds) {}

    static String app(Params p) {
        String cluster = p.name() + "-cluster";
        String domain = cluster + "." + p.namespace() + ".svc.cluster.local";
        List<String> seeds = new ArrayList<>();
        for (int i = 0; i < p.replicas(); i++) seeds.add("pekko://strata@" + p.name() + "-" + i + "." + domain + ":" + p.remotingPort());
        String jdbc = p.postgres() ? "jdbc:postgresql://" + p.name() + "-db:5432/" + p.database() : p.jdbcUrl();
        StringBuilder env = new StringBuilder();
        env(env, "STRATA_CLUSTER_MODE", "seed-nodes");
        // Every node is a seed: a restarted node rejoins the others instead of forming its own cluster.
        env(env, "STRATA_SEED_NODES", String.join(",", seeds));
        env(env, "STRATA_HOST", "$(POD_NAME)." + domain);
        env(env, "STRATA_BIND_HOST", "0.0.0.0");
        env(env, "STRATA_PORT", String.valueOf(p.remotingPort()));
        env(env, "STRATA_HTTP_PORT", String.valueOf(p.httpPort()));
        env(env, "STRATA_STORE", "jdbc");
        env(env, "STRATA_SPLIT_BRAIN", p.splitBrain());
        if (jdbc != null && !jdbc.isBlank()) env(env, "STRATA_JDBC_URL", jdbc);
        env.append(secretEnv("STRATA_JDBC_USER", p.name() + "-db", "user"));
        env.append(secretEnv("STRATA_JDBC_PASSWORD", p.name() + "-db", "password"));
        env(env, "JAVA_OPTS", "-XX:MaxRAMPercentage=" + p.maxRamPercentage());
        boolean tls = p.tlsSecret() != null && !p.tlsSecret().isBlank();
        if (tls) {
            // Node-to-node TLS from PEM files that the Secret's owner (e.g. cert-manager) rotates.
            env(env, "STRATA_TLS", "pem");
            env(env, "STRATA_TLS_DIR", p.tlsMountPath());
        }
        p.env().forEach((k, v) -> env(env, k, v));

        return """
                # Generated by the Strata Gradle plugin (strataManifests). Change strata { kubernetes { } } instead.
                apiVersion: v1
                kind: Service
                metadata:
                  name: %1$s
                  namespace: %3$s
                  labels: {app.kubernetes.io/name: %2$s}
                spec:
                  # Headless, and published before pods are ready, so starting nodes can find each other.
                  clusterIP: None
                  publishNotReadyAddresses: true
                  selector: {app.kubernetes.io/name: %2$s}
                  ports:
                    - {name: remoting, port: %4$d, targetPort: remoting}
                ---
                apiVersion: v1
                kind: Service
                metadata:
                  name: %2$s
                  namespace: %3$s
                  labels: {app.kubernetes.io/name: %2$s}
                spec:
                  type: %5$s
                  selector: {app.kubernetes.io/name: %2$s}
                  ports:
                    - {name: http, port: %6$d, targetPort: http}
                ---
                apiVersion: apps/v1
                kind: StatefulSet
                metadata:
                  name: %2$s
                  namespace: %3$s
                  labels: {app.kubernetes.io/name: %2$s}
                spec:
                  serviceName: %1$s
                  replicas: %7$d
                  podManagementPolicy: Parallel
                  selector:
                    matchLabels: {app.kubernetes.io/name: %2$s}
                  template:
                    metadata:
                      labels: {app.kubernetes.io/name: %2$s}
                      annotations:
                        prometheus.io/scrape: "true"
                        prometheus.io/port: "%6$d"
                        prometheus.io/path: "%8$s/metrics"
                    spec:
                      # Time to hand entities over to the remaining nodes when a pod stops.
                      terminationGracePeriodSeconds: %9$d
                      containers:
                        - name: strata
                          image: %10$s
                          imagePullPolicy: IfNotPresent
                          ports:
                            - {name: http, containerPort: %6$d}
                            - {name: remoting, containerPort: %4$d}
                          env:
                            - name: POD_NAME
                              valueFrom: {fieldRef: {fieldPath: metadata.name}}
                %11$s
                          # A node serves once it has joined its cluster; until then only this probe runs,
                          # so a slow start isn't taken for a hang.
                          startupProbe:
                            httpGet: {path: %8$s/health/live, port: http}
                            periodSeconds: 5
                            failureThreshold: %15$d
                          readinessProbe:
                            httpGet: {path: %8$s/health/ready, port: http}
                            periodSeconds: 5
                          # Fails once the node has been removed from its cluster, so it's restarted and rejoins.
                          livenessProbe:
                            httpGet: {path: %8$s/health/live, port: http}
                            periodSeconds: 10
                          resources:
                            requests: {cpu: %12$s, memory: %13$s}
                            limits: {memory: %13$s}
                %14$s
                ---
                apiVersion: policy/v1
                kind: PodDisruptionBudget
                metadata:
                  name: %2$s
                  namespace: %3$s
                spec:
                  maxUnavailable: 1
                  selector:
                    matchLabels: {app.kubernetes.io/name: %2$s}
                """.formatted(cluster, p.name(), p.namespace(), p.remotingPort(), p.serviceType(), p.httpPort(), p.replicas(),
                p.managementBase(), p.graceSeconds(), p.image(), env.toString().stripTrailing(), p.cpu(), p.memory(),
                tls ? """
                          volumeMounts:
                            - {name: tls, mountPath: %s, readOnly: true}
                      volumes:
                        - name: tls
                          secret: {secretName: %s}""".formatted(p.tlsMountPath(), p.tlsSecret()).stripIndent().indent(6).stripTrailing() : "",
                Math.max(1, (p.startupSeconds() + 4) / 5));
    }

    /** The Secret with database credentials (shared by the app and the development database). */
    static String secret(Params p, String password) {
        return """
                # Generated by the Strata Gradle plugin. The password is kept in .strata/ next to the build.
                apiVersion: v1
                kind: Secret
                metadata:
                  name: %s-db
                  namespace: %s
                type: Opaque
                stringData:
                  user: %s
                  password: "%s"
                """.formatted(p.name(), p.namespace(), p.user(), password);
    }

    static String postgres(Params p) {
        return """
                # Generated by the Strata Gradle plugin: a PostgreSQL for development only.
                apiVersion: v1
                kind: PersistentVolumeClaim
                metadata:
                  name: %1$s-db
                  namespace: %2$s
                spec:
                  accessModes: [ReadWriteOnce]
                  resources:
                    requests: {storage: %3$s}
                ---
                apiVersion: v1
                kind: Service
                metadata:
                  name: %1$s-db
                  namespace: %2$s
                spec:
                  selector: {app.kubernetes.io/name: %1$s-db}
                  ports:
                    - {name: postgres, port: 5432, targetPort: 5432}
                ---
                apiVersion: apps/v1
                kind: Deployment
                metadata:
                  name: %1$s-db
                  namespace: %2$s
                spec:
                  replicas: 1
                  strategy: {type: Recreate}
                  selector:
                    matchLabels: {app.kubernetes.io/name: %1$s-db}
                  template:
                    metadata:
                      labels: {app.kubernetes.io/name: %1$s-db}
                    spec:
                      containers:
                        - name: postgres
                          image: %4$s
                          ports:
                            - {containerPort: 5432}
                          env:
                            - {name: POSTGRES_DB, value: %5$s}
                            - name: POSTGRES_USER
                              valueFrom: {secretKeyRef: {name: %1$s-db, key: user}}
                            - name: POSTGRES_PASSWORD
                              valueFrom: {secretKeyRef: {name: %1$s-db, key: password}}
                            - {name: PGDATA, value: /var/lib/postgresql/data/pgdata}
                          readinessProbe:
                            exec: {command: [pg_isready, -U, %6$s]}
                            periodSeconds: 5
                          volumeMounts:
                            - {name: data, mountPath: /var/lib/postgresql/data}
                      volumes:
                        - name: data
                          persistentVolumeClaim: {claimName: %1$s-db}
                """.formatted(p.name(), p.namespace(), p.postgresStorage(), p.postgresImage(), p.database(), p.user());
    }

    private static void env(StringBuilder b, String name, String value) {
        b.append("            - {name: ").append(name).append(", value: ").append(quote(value)).append("}\n");
    }

    private static String secretEnv(String name, String secret, String key) {
        return "            - name: " + name + "\n              valueFrom: {secretKeyRef: {name: " + secret + ", key: " + key + "}}\n";
    }

    /** A YAML double-quoted string. */
    static String quote(String v) {
        return "\"" + v.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }
}
