package io.strata.gradle;

import org.gradle.api.DefaultTask;
import org.gradle.api.GradleException;
import org.gradle.api.file.DirectoryProperty;
import org.gradle.api.file.RegularFileProperty;
import org.gradle.api.provider.ListProperty;
import org.gradle.api.provider.MapProperty;
import org.gradle.api.provider.Property;
import org.gradle.api.tasks.Input;
import org.gradle.api.tasks.InputDirectory;
import org.gradle.api.tasks.Internal;
import org.gradle.api.tasks.OutputDirectory;
import org.gradle.api.tasks.TaskAction;
import org.gradle.process.ExecOperations;

import javax.inject.Inject;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.security.SecureRandom;
import java.util.ArrayList;
import java.util.HexFormat;
import java.util.List;

/** The image and Kubernetes tasks the plugin registers. */
final class DeployTasks {
    private DeployTasks() {}

    /** Writes a Dockerfile next to a copy of the app's distribution ({@code installDist}). */
    public abstract static class Dockerfile extends DefaultTask {
        @InputDirectory public abstract DirectoryProperty getDistribution();
        @Input public abstract Property<String> getBase();
        @Input public abstract Property<String> getAppName();
        @Input public abstract ListProperty<Integer> getPorts();
        @OutputDirectory public abstract DirectoryProperty getContext();
        @Inject protected abstract org.gradle.api.file.FileSystemOperations getFs();

        @TaskAction
        public void write() throws IOException {
            Path ctx = getContext().get().getAsFile().toPath();
            getFs().delete(d -> d.delete(ctx.toFile()));
            getFs().copy(c -> c.from(getDistribution()).into(ctx.resolve("app")));
            String expose = String.join(" ", getPorts().get().stream().map(String::valueOf).toList());
            Files.writeString(ctx.resolve("Dockerfile"), """
                    # Generated by the Strata Gradle plugin (strataDockerfile).
                    FROM %s
                    WORKDIR /app
                    COPY app/ /app/
                    # Not root. The start script already carries the JVM flags Strata needs.
                    USER 1000
                    EXPOSE %s
                    ENTRYPOINT ["/app/bin/%s"]
                    """.formatted(getBase().get(), expose, getAppName().get()));
        }
    }

    /** Runs command lines in order, failing on the first that fails. */
    public abstract static class Commands extends DefaultTask {
        @Input public abstract ListProperty<List<String>> getCommands();
        @Inject protected abstract ExecOperations getExec();

        @TaskAction
        public void run() {
            for (List<String> cmd : getCommands().get()) {
                getLogger().lifecycle("> " + String.join(" ", cmd));
                try {
                    getExec().exec(e -> e.commandLine(cmd));
                } catch (RuntimeException ex) {
                    throw new GradleException("Failed: " + String.join(" ", cmd) + " (is " + cmd.get(0) + " installed and its cluster running?)", ex);
                }
            }
        }
    }

    /** Writes the Kubernetes manifests: app.yaml, secret.yaml and (dev) postgres.yaml. */
    public abstract static class ManifestsTask extends DefaultTask {
        @Input public abstract Property<String> getAppName();
        @Input public abstract Property<String> getNamespace();
        @Input public abstract Property<String> getImage();
        @Input public abstract Property<Integer> getReplicas();
        @Input public abstract Property<Integer> getHttpPort();
        @Input public abstract Property<Integer> getRemotingPort();
        @Input public abstract Property<String> getServiceType();
        @Input public abstract Property<String> getCpu();
        @Input public abstract Property<String> getMemory();
        @Input public abstract Property<Integer> getMaxRamPercentage();
        @Input public abstract Property<Integer> getGraceSeconds();
        @Input public abstract Property<String> getManagementBase();
        @Input public abstract Property<Boolean> getPostgres();
        @Input public abstract Property<String> getPostgresImage();
        @Input public abstract Property<String> getPostgresStorage();
        @Input public abstract Property<String> getDatabase();
        @Input public abstract Property<String> getUser();
        @Input public abstract Property<String> getJdbcUrl();
        @Input public abstract MapProperty<String, String> getEnv();
        @Input public abstract Property<String> getTlsSecret();
        @Input public abstract Property<String> getTlsMountPath();
        /** Where the development database password is kept between builds (not under build/). */
        @Internal public abstract RegularFileProperty getPasswordFile();
        @OutputDirectory public abstract DirectoryProperty getOutput();

        @TaskAction
        public void write() throws IOException {
            if (!getPostgres().get() && getJdbcUrl().get().isBlank()) {
                throw new GradleException("strata.kubernetes: set jdbcUrl, or postgres = true for a development database");
            }
            var p = new Manifests.Params(getAppName().get(), getNamespace().get(), getImage().get(), getReplicas().get(), getHttpPort().get(),
                    getRemotingPort().get(), getServiceType().get(), getCpu().get(), getMemory().get(), getMaxRamPercentage().get(),
                    getGraceSeconds().get(), getManagementBase().get(), getPostgres().get(), getPostgresImage().get(),
                    getPostgresStorage().get(), getDatabase().get(), getUser().get(), getJdbcUrl().get(), getEnv().get(),
                    getTlsSecret().get(), getTlsMountPath().get());
            Path out = getOutput().get().getAsFile().toPath();
            Files.createDirectories(out);
            Files.writeString(out.resolve("app.yaml"), Manifests.app(p));
            if (p.postgres()) {
                Files.writeString(out.resolve("secret.yaml"), Manifests.secret(p, password()));
                Files.writeString(out.resolve("postgres.yaml"), Manifests.postgres(p));
            } else {
                Files.deleteIfExists(out.resolve("secret.yaml"));
                Files.deleteIfExists(out.resolve("postgres.yaml"));
            }
        }

        /** A random password, made once and reused, so the database keeps accepting it. */
        private String password() throws IOException {
            Path f = getPasswordFile().get().getAsFile().toPath();
            if (Files.exists(f)) return Files.readString(f).trim();
            byte[] b = new byte[18];
            new SecureRandom().nextBytes(b);
            String pw = HexFormat.of().formatHex(b);
            Files.createDirectories(f.getParent());
            Files.writeString(f, pw + "\n");
            try {
                Files.setPosixFilePermissions(f, java.nio.file.attribute.PosixFilePermissions.fromString("rw-------"));
            } catch (UnsupportedOperationException ignored) {
                // not a POSIX file system
            }
            Files.writeString(f.getParent().resolve(".gitignore"), "*\n");
            return pw;
        }
    }

    static List<List<String>> loadCommands(String how, String image, KubernetesSpec k, ImageSpec img) {
        List<List<String>> out = new ArrayList<>();
        switch (how) {
            case "minikube" -> out.add(List.of(k.getMinikube().get(), "image", "load", image));
            case "kind" -> out.add(List.of(k.getKind().get(), "load", "docker-image", image));
            case "push" -> out.add(List.of(img.getBuilder().get(), "push", image));
            case "none" -> { }
            default -> throw new GradleException("strata.kubernetes.load must be minikube, kind, push or none, not " + how);
        }
        return out;
    }
}
